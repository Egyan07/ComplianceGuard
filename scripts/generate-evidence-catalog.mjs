#!/usr/bin/env node
/**
 * Generate the frontend evidence catalog from the CANONICAL shared data.
 *
 * Source of truth (single authoritative vocabulary):
 *   - shared/frameworks/soc2_controls.yaml          → per-control required evidence
 *   - shared/frameworks/evidence-vocabulary.json    → canonical type metadata
 *
 * Output:
 *   - frontend/src/components/evidenceCatalog.generated.ts
 *
 * The generated module is the ONLY catalog the upload UI may expose. Every type
 * a user can select is by construction a canonical type the scoring engine
 * accepts for that control — the Phase 10 "97 dead upload types" class of bug
 * cannot return.
 *
 * Usage:
 *   node scripts/generate-evidence-catalog.mjs          # write the file
 *   node scripts/generate-evidence-catalog.mjs --check  # verify the committed file is current (CI)
 */
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = path.resolve(__dirname, '..');

// Resolve js-yaml from the FRONTEND install, not the repo root. CI jobs that
// run this script (lint-and-test's check:evidence, e2e's predev/prebuild) only
// run `npm ci` inside frontend/, so the root node_modules does not exist there.
// js-yaml is declared in frontend/package.json, so this always resolves.
const _require = createRequire(path.join(REPO_ROOT, 'frontend', 'package.json'));
const yaml = _require('js-yaml');
const SHARED_DIR = path.join(REPO_ROOT, 'shared', 'frameworks');
const OUT_FILE = path.join(REPO_ROOT, 'frontend', 'src', 'components', 'evidenceCatalog.generated.ts');

// Canonical type → desktop storage category. Must be one of the categories
// validated by electron/processing/evidence-processor.js (ALLOWED_CATEGORIES).
const CATEGORY_BY_TYPE = {
  access_logs: 'SystemLogs',
  audit_reports: 'Documents',
  backup_logs: 'BackupFiles',
  encryption_policies: 'SecurityPolicies',
  event_logs: 'SystemLogs',
  firewall_configs: 'ConfigFiles',
  incident_reports: 'Documents',
  network_configs: 'NetworkConfigs',
  policy_document: 'Documents',
  security_policies: 'SecurityPolicies',
  system_configs: 'ConfigFiles',
  training_records: 'Documents',
  user_provisioning: 'Documents',
};

function readShared(name) {
  const raw = fs.readFileSync(path.join(SHARED_DIR, name), 'utf8');
  return name.endsWith('.json') ? JSON.parse(raw) : yaml.load(raw);
}

function main() {
  const soc2 = readShared('soc2_controls.yaml');
  const vocab = readShared('evidence-vocabulary.json');

  const canonicalTypes = {};
  for (const entry of vocab.canonical_types) {
    canonicalTypes[entry.type] = {
      description: entry.description,
      category: CATEGORY_BY_TYPE[entry.type] || 'Documents',
      aliases: entry.legacy_aliases || [],
    };
  }

  const controls = (soc2.controls || []).map((c) => {
    const types = [...new Set(c.required_evidence || [])].sort();
    for (const t of types) {
      if (!canonicalTypes[t]) {
        throw new Error(
          `soc2_controls.yaml control ${c.id} requires '${t}', which is not a canonical ` +
            `type in evidence-vocabulary.json — fix the canonical data, not the catalog.`
        );
      }
    }
    return {
      id: c.id,
      title: `${c.id} - ${c.title}`,
      types,
    };
  });

  const lines = [];
  lines.push('// AUTO-GENERATED by scripts/generate-evidence-catalog.mjs — DO NOT EDIT.');
  lines.push('// Source of truth: shared/frameworks/soc2_controls.yaml + shared/frameworks/evidence-vocabulary.json.');
  lines.push('// Regenerate with: npm run generate:evidence  (CI verifies freshness via check:evidence)');
  lines.push('');
  lines.push('export interface Soc2ControlOption {');
  lines.push('  id: string;');
  lines.push('  title: string;');
  lines.push('  /** Canonical evidence types the scoring engine accepts for this control. */');
  lines.push('  types: string[];');
  lines.push('}');
  lines.push('');
  lines.push('export const SOC2_CONTROLS: Soc2ControlOption[] = [');
  for (const c of controls) {
    lines.push(`  { id: ${JSON.stringify(c.id)}, title: ${JSON.stringify(c.title)}, types: ${JSON.stringify(c.types)} },`);
  }
  lines.push('];');
  lines.push('');
  lines.push('export interface CanonicalEvidenceType {');
  lines.push('  description: string;');
  lines.push('  category: string;');
  lines.push('  aliases: string[];');
  lines.push('}');
  lines.push('');
  lines.push('export const CANONICAL_EVIDENCE_TYPES: Record<string, CanonicalEvidenceType> = {');
  for (const [type, meta] of Object.entries(canonicalTypes).sort()) {
    lines.push(`  ${JSON.stringify(type)}: ${JSON.stringify(meta)},`);
  }
  lines.push('};');
  lines.push('');
  lines.push('/** Map a canonical evidence type to its desktop storage category. */');
  lines.push('export function getCategoryForType(evidenceType: string): string {');
  lines.push('  return CANONICAL_EVIDENCE_TYPES[evidenceType]?.category ?? "Documents";');
  lines.push('}');
  lines.push('');

  const content = lines.join('\n');

  if (process.argv.includes('--check')) {
    if (!fs.existsSync(OUT_FILE)) {
      console.error('check:evidence: generated catalog missing — run `npm run generate:evidence`');
      process.exit(1);
    }
    const current = fs.readFileSync(OUT_FILE, 'utf8');
    if (current !== content) {
      console.error(
        'check:evidence: evidenceCatalog.generated.ts is stale. Run `npm run generate:evidence` ' +
          'and commit the result.'
      );
      process.exit(1);
    }
    console.log(`check:evidence: OK — ${controls.length} SOC 2 controls, ${Object.keys(canonicalTypes).length} canonical evidence types.`);
    return;
  }

  fs.mkdirSync(path.dirname(OUT_FILE), { recursive: true });
  fs.writeFileSync(OUT_FILE, content, 'utf8');
  console.log(`Generated ${path.relative(REPO_ROOT, OUT_FILE)} (${controls.length} controls, ${Object.keys(canonicalTypes).length} evidence types).`);
}

main();
